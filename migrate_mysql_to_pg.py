@tool
def create_postgres_schema() -> str:
    """Create PostgreSQL base tables, primary/unique keys, indexes and foreign keys from MySQL metadata."""
    mc = mysql_connection()
    pc = pg_connection()
    mcur = mc.cursor(dictionary=True)
    pcur = pc.cursor()
    db = MYSQL_CFG["database"]
    try:
        mcur.execute("""SELECT TABLE_NAME,COLUMN_NAME,ORDINAL_POSITION,COLUMN_TYPE,
                    IS_NULLABLE, COLUMN_DEFAULT, EXTRA
                    FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=%s
                    ORDER BY TABLE_NAME,ORDINAL_POSITION""", (db,))
        columns = mcur.fetchall()
        mcur.execute("""SELECT TABLE_NAME,INDEX_NAME,NON_UNIQUE,SEQ_IN_INDEX,COLUMN_NAME
                    FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=%s
                    ORDER BY TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX""", (db,))
        indexes = mcur.fetchall()
        mcur.execute("""SELECT TABLE_NAME,CONSTRAINT_NAME,COLUMN_NAME,
                    REFERENCED_TABLE_NAME,REFERENCED_COLUMN_NAME,ORDINAL_POSITION
                    FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA=%s
                    AND REFERENCED_TABLE_NAME IS NOT NULL
                    ORDER BY TABLE_NAME,CONSTRAINT_NAME,ORDINAL_POSITION""", (db,))
        fks = mcur.fetchall()

        def pg_type(mysql_type):
            t = mysql_type.lower()
            if t.startswith("tinyint(1)"): return "BOOLEAN"
            if t.startswith("tinyint"): return "SMALLINT"
            if t.startswith("smallint"): return "INTEGER" if "unsigned" in t else "SMALLINT"
            if t.startswith("mediumint"): return "INTEGER"
            if t.startswith("int") or t.startswith("integer"): return "BIGINT" if "unsigned" in t else "INTEGER"
            if t.startswith("bigint"): return "NUMERIC(20,0)" if "unsigned" in t else "BIGINT"
            if t.startswith("decimal") or t.startswith("numeric"): return mysql_type.upper().replace("UNSIGNED", "")
            if t.startswith("float"): return "REAL"
            if t.startswith("double"): return "DOUBLE PRECISION"
            if t.startswith("enum") or t.startswith("set"): return "TEXT"
            if t.startswith(("varchar", "char", "binary", "varbinary")): return "TEXT" if "text" not in t else "BYTEA"
            if "blob" in t or "binary" in t: return "BYTEA"
            if "text" in t or t == "json": return "JSONB" if t == "json" else "TEXT"
            if t == "date": return "DATE"
            if t.startswith("datetime"): return "TIMESTAMP"
            if t.startswith("timestamp"): return "TIMESTAMPTZ"
            if t.startswith("time"): return "TIME"
            if t.startswith("year"): return "SMALLINT"
            return "TEXT"

        grouped = {}
        for col in columns:
            grouped.setdefault(col["TABLE_NAME"], []).append(col)
        index_groups = {}
        for idx in indexes:
            index_groups.setdefault((idx["TABLE_NAME"], idx["INDEX_NAME"]), []).append(idx)
        for table, cols in grouped.items():
            definitions = []
            primary = [i["COLUMN_NAME"] for i in index_groups.get((table, "PRIMARY"), [])]
            for col in cols:
                name = col["COLUMN_NAME"].lower()
                typ = pg_type(col["COLUMN_TYPE"])
                identity = " GENERATED BY DEFAULT AS IDENTITY" if "auto_increment" in col["EXTRA"].lower() else ""
                nullable = " NOT NULL" if col["IS_NULLABLE"] == "NO" else ""
                default = ""
                if col["COLUMN_DEFAULT"] is not None and "auto_increment" not in col["EXTRA"].lower():
                    d = str(col["COLUMN_DEFAULT"])
                    if d.upper() in ("CURRENT_TIMESTAMP", "CURRENT_TIMESTAMP()"):
                        default = " DEFAULT CURRENT_TIMESTAMP"
                    elif d.upper() in ("CURRENT_DATE",):
                        default = " DEFAULT CURRENT_DATE"
                    elif d in ("0", "1") or (d.startswith("'") and d.endswith("'")):
                        default = " DEFAULT " + d
                definitions.append(pgsql.SQL("{} {}{}{}{}").format(
                    pgsql.Identifier(name), pgsql.SQL(typ), pgsql.SQL(identity),
                    pgsql.SQL(nullable), pgsql.SQL(default)))
            if primary:
                definitions.append(pgsql.SQL("PRIMARY KEY ({})").format(
                    pgsql.SQL(",").join(pgsql.Identifier(c.lower()) for c in primary)))
            for (idx_table, idx_name), idx_cols in index_groups.items():
                if idx_table == table and idx_name != "PRIMARY" and not idx_cols[0]["NON_UNIQUE"]:
                    definitions.append(pgsql.SQL("UNIQUE ({})").format(
                        pgsql.SQL(",").join(pgsql.Identifier(i["COLUMN_NAME"].lower()) for i in idx_cols)))
            stmt = pgsql.SQL("CREATE TABLE IF NOT EXISTS {} ({})").format(
                pgsql.Identifier(table.lower()), pgsql.SQL(", ").join(definitions))
            pcur.execute(stmt)

        # Add foreign keys only after all tables exist.
        fk_groups = {}
        for fk in fks:
            fk_groups.setdefault((fk["TABLE_NAME"], fk["CONSTRAINT_NAME"], fk["REFERENCED_TABLE_NAME"]), []).append(fk)
        for (table, constraint, ref_table), parts in fk_groups.items():
            cols = [x["COLUMN_NAME"].lower() for x in parts]
            ref_cols = [x["REFERENCED_COLUMN_NAME"].lower() for x in parts]
            stmt = pgsql.SQL("ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})").format(
                pgsql.Identifier(table.lower()), pgsql.Identifier(constraint.lower()),
                pgsql.SQL(",").join(pgsql.Identifier(x) for x in cols),
                pgsql.Identifier(ref_table.lower()),
                pgsql.SQL(",").join(pgsql.Identifier(x) for x in ref_cols))
            pcur.execute("SELECT 1 FROM pg_constraint WHERE conname = %s", (constraint.lower(),))
            if not pcur.fetchone():
                pcur.execute(stmt)
        # Add ordinary indexes after the table definitions.
        for (table, idx_name), idx_cols in index_groups.items():
            if idx_name == "PRIMARY" or not idx_cols[0]["NON_UNIQUE"]:
                continue
            idx = (table + "_" + idx_name).lower()[:63]
            stmt = pgsql.SQL("CREATE INDEX IF NOT EXISTS {} ON {} ({})").format(
                pgsql.Identifier(idx), pgsql.Identifier(table.lower()),
                pgsql.SQL(",").join(pgsql.Identifier(i["COLUMN_NAME"].lower()) for i in idx_cols))
            pcur.execute(stmt)
        pc.commit()
        return f"Created/confirmed {len(grouped)} PostgreSQL base tables, keys and indexes. ENUM/SET mapped to TEXT; review business semantics."
    except Exception as exc:
        pc.rollback()
        return f"Schema creation failed and rolled back: {exc}"
    finally:
        mcur.close(); pcur.close(); mc.close(); pc.close()


@tool
def inspect_mysql_source() -> str:
    """Read MySQL tables, columns, indexes, foreign keys, views, routines, triggers and row counts."""
    conn = mysql_connection()
    cur = conn.cursor(dictionary=True)
    db = MYSQL_CFG["database"]
    try:
        cur.execute("""SELECT TABLE_NAME, TABLE_TYPE, ENGINE, TABLE_ROWS
                       FROM information_schema.TABLES WHERE TABLE_SCHEMA=%s""", (db,))
        tables = cur.fetchall()
        cur.execute("""SELECT TABLE_NAME,COLUMN_NAME,ORDINAL_POSITION,COLUMN_TYPE,
                    IS_NULLABLE,COLUMN_DEFAULT,EXTRA,COLUMN_COMMENT
                    FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=%s
                    ORDER BY TABLE_NAME,ORDINAL_POSITION""", (db,))
        columns = cur.fetchall()
        cur.execute("""SELECT TABLE_NAME,INDEX_NAME,NON_UNIQUE,SEQ_IN_INDEX,COLUMN_NAME
                    FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=%s
                    ORDER BY TABLE_NAME,INDEX_NAME,SEQ_IN_INDEX""", (db,))
        indexes = cur.fetchall()
        cur.execute("""SELECT TABLE_NAME,COLUMN_NAME,CONSTRAINT_NAME,
                    REFERENCED_TABLE_NAME,REFERENCED_COLUMN_NAME
                    FROM information_schema.KEY_COLUMN_USAGE
                    WHERE TABLE_SCHEMA=%s AND REFERENCED_TABLE_NAME IS NOT NULL""", (db,))
        fks = cur.fetchall()
        cur.execute("""SELECT TABLE_NAME,VIEW_DEFINITION FROM information_schema.VIEWS
                    WHERE TABLE_SCHEMA=%s""", (db,))
        views = cur.fetchall()
        cur.execute("""SELECT ROUTINE_TYPE,ROUTINE_NAME,DATA_TYPE,ROUTINE_DEFINITION
                    FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA=%s""", (db,))
        routines = cur.fetchall()
        cur.execute("""SELECT TRIGGER_NAME,ACTION_TIMING,EVENT_MANIPULATION,
                    EVENT_OBJECT_TABLE,ACTION_STATEMENT FROM information_schema.TRIGGERS
                    WHERE TRIGGER_SCHEMA=%s""", (db,))
        triggers = cur.fetchall()
        # Exact counts are more useful than information_schema estimates.
        counts = {}
        for row in tables:
            if row["TABLE_TYPE"] == "BASE TABLE":
                name = row["TABLE_NAME"]
                cur.execute("SELECT COUNT(*) AS n FROM " + "`" + name.replace("`", "``") + "`")
                counts[name] = cur.fetchone()["n"]
        return json.dumps({"tables": tables, "columns": columns, "indexes": indexes,
                           "foreign_keys": fks, "views": views, "routines": routines,
                           "triggers": triggers, "exact_row_counts": counts}, default=str)
    finally:
        cur.close()
        conn.close()


@tool
def get_mysql_create_statement(table_name: str) -> str:
    """Return SHOW CREATE TABLE for one named source table."""
    conn = mysql_connection()
    cur = conn.cursor()
    try:
        # Parameterize the identifier using MySQL's identifier quoting.
        safe = table_name.replace("`", "``")
        cur.execute(f"SHOW CREATE TABLE `{safe}`")
        row = cur.fetchone()
        if not row:
            return f"No table found: {table_name}"
        return row[1]
    finally:
        cur.close()
        conn.close()


@tool
def apply_postgres_ddl(statements: str) -> str:
    """Apply one model-translated PostgreSQL CREATE/ALTER/COMMENT statement, including a complete function definition. Destructive SQL is rejected."""
    allowed = ("CREATE ", "ALTER ", "COMMENT ", "DO ")
    chunks = [s.strip() for s in statements.split(";") if s.strip()]
    if not chunks:
        return "Rejected: no SQL statements supplied."
    for chunk in chunks:
        normalized = chunk.lstrip().upper()
        if not normalized.startswith(allowed) or any(x in normalized for x in
            ("DROP ", "TRUNCATE ", "DELETE ", "UPDATE ", "INSERT ", "COPY ")):
            return "Rejected: only CREATE, ALTER, COMMENT, and DO statements are allowed; destructive/data SQL is blocked."
    conn = pg_connection()
    conn.autocommit = False
    cur = conn.cursor()
    results = []
    try:
        for statement in chunks:
            cur.execute(statement)
            results.append("SUCCESS")
        conn.commit()
        return f"Applied {len(chunks)} DDL statement(s): " + ", ".join(results)
    except Exception as exc:
        conn.rollback()
        return f"DDL failed and transaction rolled back: {exc}"
    finally:
        cur.close()
        conn.close()


@tool
def migrate_table_data(table_name: str, batch_size: int = 1000) -> str:
    """Copy one table into its existing PostgreSQL counterpart in batches; returns copied row count."""
    if batch_size < 1 or batch_size > 10000:
        return "batch_size must be between 1 and 10000"
    mc = mysql_connection()
    pc = pg_connection()
    mcur = mc.cursor()
    pcur = pc.cursor()
    try:
        safe = table_name.replace("`", "``")
        mcur.execute(f"SELECT * FROM `{safe}`")
        source_columns = [d[0] for d in mcur.description]
        target_cols = [c.lower() for c in source_columns]
        insert = pgsql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
            pgsql.Identifier(table_name.lower()),
            pgsql.SQL(",").join(pgsql.Identifier(c) for c in target_cols),
            pgsql.SQL(",").join(pgsql.Placeholder() for _ in target_cols),
        )
        count = 0
        while True:
            rows = mcur.fetchmany(batch_size)
            if not rows:
                break
            cleaned = []
            for row in rows:
                vals = []
                for value in row:
                    if isinstance(value, str) and value.startswith("0000-00-00"):
                        value = None
                    vals.append(value)
                cleaned.append(tuple(vals))
            pcur.executemany(insert, cleaned)
            count += len(cleaned)
        pc.commit()
        return f"{table_name}: inserted {count} rows"
    except Exception as exc:
        pc.rollback()
        return f"{table_name}: data load failed and rolled back: {exc}"
    finally:
        mcur.close(); pcur.close(); mc.close(); pc.close()


@tool
def validate_migration(table_names: str) -> str:
    """Compare exact source and target row counts for comma-separated table names."""
    names = [n.strip() for n in table_names.split(",") if n.strip()]
    mc = mysql_connection(); pc = pg_connection()
    mcur = mc.cursor(); pcur = pc.cursor()
    report = []
    try:
        for name in names:
            safe = name.replace("`", "``")
            mcur.execute(f"SELECT COUNT(*) FROM `{safe}`")
            source_count = mcur.fetchone()[0]
            pcur.execute(pgsql.SQL("SELECT COUNT(*) FROM {}").format(pgsql.Identifier(name.lower())))
            target_count = pcur.fetchone()[0]
            report.append({"table": name, "mysql": source_count, "postgres": target_count,
                           "match": source_count == target_count})
        return json.dumps(report)
    except Exception as exc:
        return f"Validation failed: {exc}"
    finally:
        mcur.close(); pcur.close(); mc.close(); pc.close()


